import { BadRequestException, Injectable, Logger } from '@nestjs/common';

@Injectable()
export class SqlValidatorService {
  private readonly logger = new Logger(SqlValidatorService.name);

  // Strictly prohibited DDL, DML, or administrative commands
  private readonly FORBIDDEN_KEYWORDS = [
    'INSERT',
    'UPDATE',
    'DELETE',
    'DROP',
    'ALTER',
    'TRUNCATE',
    'CREATE',
    'RENAME',
    'GRANT',
    'REVOKE',
    'COPY',
    'EXECUTE',
    'CALL',
    'VACUUM',
    'MERGE',
    'UPSERT',
    'DO',
    'PREPARE',
    'DEALLOCATE',
    'SET',
    'RESET',
    'LOCK',
    'EXPLAIN ANALYZE',
  ];

  // Dangerous PostgreSQL internal functions/tables
  private readonly FORBIDDEN_PATTERNS = [
    /pg_read_file/i,
    /pg_write_file/i,
    /pg_sleep/i,
    /dblink/i,
    /lo_import/i,
    /lo_export/i,
    /pg_shadow/i,
    /pg_authid/i,
    /information_schema\.user_privileges/i,
  ];

  /**
   * Validates and sanitizes an AI-generated SQL query for read-only execution
   * and multi-tenant security.
   *
   * @param sql Raw SQL query generated by LLM
   * @param tenantId The authenticated tenant ID that MUST be filtered
   * @returns Cleaned, safe SQL string ready for execution
   */
  validateAndSanitize(sql: string, tenantId: string): string {
    if (!sql || typeof sql !== 'string') {
      throw new BadRequestException('SQL query is empty or invalid.');
    }

    // 1. Strip markdown fences if OpenAI wrapped it in ```sql ... ```
    let cleanSql = sql
      .replace(/^```(sql)?/i, '')
      .replace(/```$/, '')
      .trim();

    // 2. Reject queries with statement chaining (semicolon outside single quotes)
    const withoutQuotes = cleanSql.replace(/'(?:''|[^'])*'/g, '');
    const statements = withoutQuotes
      .split(';')
      .map((s) => s.trim())
      .filter(Boolean);

    if (statements.length > 1) {
      this.logger.warn(`Rejected multi-statement SQL: ${cleanSql}`);
      throw new BadRequestException(
        'Security rejection: Multi-statement SQL is strictly prohibited.',
      );
    }

    // Remove any trailing semicolon
    cleanSql = cleanSql.replace(/;+\s*$/, '').trim();

    // 3. Strictly verify query starts with SELECT or WITH (for CTEs)
    const upper = cleanSql.toUpperCase();
    const startsWithSelect = upper.startsWith('SELECT');
    const startsWithWith = upper.startsWith('WITH');

    if (!startsWithSelect && !startsWithWith) {
      this.logger.warn(`Rejected non-SELECT statement: ${cleanSql}`);
      throw new BadRequestException(
        'Security rejection: Only read-only SELECT queries are allowed.',
      );
    }

    // 4. Check for forbidden keywords (tokenized)
    const tokens = upper.split(/[\s,();]+/);
    for (const token of tokens) {
      if (this.FORBIDDEN_KEYWORDS.includes(token)) {
        this.logger.warn(`Forbidden keyword [${token}] detected in: ${cleanSql}`);
        throw new BadRequestException(
          `Security rejection: Command '${token}' is not permitted in read-only queries.`,
        );
      }
    }

    // 5. Check for dangerous internal functions or tables
    for (const pattern of this.FORBIDDEN_PATTERNS) {
      if (pattern.test(cleanSql)) {
        this.logger.warn(`Forbidden pattern [${pattern}] detected in: ${cleanSql}`);
        throw new BadRequestException(
          'Security rejection: Dangerous PostgreSQL function or system catalog access.',
        );
      }
    }

    // 6. Multi-Tenant Isolation Check:
    // Ensure the query references the current tenant_id.
    const tenantNormalized = tenantId.trim().toLowerCase();
    const sqlLower = cleanSql.toLowerCase();

    if (!sqlLower.includes(tenantNormalized)) {
      this.logger.warn(
        `AI generated query without tenant filter for [${tenantId}]: ${cleanSql}`,
      );
      throw new BadRequestException(
        'Security rejection: Query does not contain required tenant isolation filter.',
      );
    }

    // 7. Enforce row limit (max 100 rows to protect memory and performance)
    if (!/LIMIT\s+\d+/i.test(cleanSql)) {
      cleanSql = `${cleanSql} LIMIT 100`;
    } else {
      // If a LIMIT exists, ensure it does not exceed 100
      cleanSql = cleanSql.replace(/LIMIT\s+(\d+)/i, (_match, limitStr) => {
        const val = parseInt(limitStr, 10);
        return `LIMIT ${Math.min(val, 100)}`;
      });
    }

    return cleanSql;
  }
}

